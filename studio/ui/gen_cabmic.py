"""The virtual mic's tables for the page: src/engine/cabmic_tables.c (tools/gen_cabmic.py) -> src/lib/cabmic_tables.ts.

    python gen_cabmic.py        (from studio/ui; run again when tools/gen_cabmic.py changes the firmware's tables)
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'src', 'engine', 'cabmic_tables.c')
OUT = os.path.join(HERE, 'src', 'lib', 'cabmic_tables.ts')
NUM = r'-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?'


def table(text, name):
    m = re.search(r'const float %s((?:\[\w+\])+) = (\{.*?\});' % name, text, re.S)
    if not m:
        raise SystemExit('%s não está em %s' % (name, SRC))
    body = re.sub(r'(%s)f' % NUM, r'\1', m.group(2)).replace('{', '[').replace('}', ']')
    body = re.sub(r',\s*\]', ']', body)
    return json.loads(body)


def main():
    text = open(SRC, encoding='utf-8').read()
    names_text = text
    text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)          # comments, inside the tables too
    names = re.search(r'cabmic_type_names\[\w+\] = \{(.*?)\};', names_text, re.S).group(1)
    out = dict(
        bands=table(text, 'cabmic_bands'), position=table(text, 'cabmic_position'),
        distance=table(text, 'cabmic_distance'), angle=table(text, 'cabmic_angle'),
        typeNames=re.findall(r'"([^"]*)"', names), typeCurve=table(text, 'cabmic_type_curve'),
        typePosition=table(text, 'cabmic_type_position'), typeDistance=table(text, 'cabmic_type_distance'),
        typeAngle=table(text, 'cabmic_type_angle'))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by studio/ui/gen_cabmic.py from src/engine/cabmic_tables.c (tools/gen_cabmic.py): the virtual\n'
                '// mic\'s curves, dB per third octave. Do not edit.\n\n')
        f.write('export const CABMIC = %s;\n' % json.dumps(out, separators=(',', ':')))
    print('%s: %d bands, %d mic types' % (OUT, len(out['bands']), len(out['typeNames'])))


if __name__ == '__main__':
    main()
