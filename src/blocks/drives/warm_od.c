struct state {
    float drive, volume;        /* Gain's taper x 0.8, Volume glided (0-1) */
    struct fos gain;
    struct fos_state gs;
    struct sos_state ts;
    struct stage st;
};

static void gain_set(struct fos *c, float g)
{
    float t = g * 168.3666229248047f;
    *c = (struct fos){ -2.1045827865600586f - t, t + 2.115428924560547f, -0.9783077239990234f };
}

static int init(void *state, void *buffer, const struct wvfx_env *env, const float *k)
{
    struct state *s = state;
    (void)buffer; (void)env;
    *s = (struct state){ 0 };
    float g = st_taper(st_pow2, k[0]);
    s->drive = g * 0.800000011920929f;
    s->volume = k[2] * 0.01f;
    gain_set(&s->gain, g);
    return 0;
}

static void process(void *state, const struct wvfx_io *io)
{
    struct state *s = state;
    float g = st_taper(st_pow2, io->knobs[0]), d = g * 0.800000011920929f, target = io->knobs[2] * 0.01f;
    int j = (int)(io->knobs[1] * 2.55f) >> 2;
    j = j < 0 ? 0 : j > 63 ? 63 : j;
    const struct sos tc = { TONE_B[3 * j], TONE_B[3 * j + 1], TONE_B[3 * j + 2], 1.0f, TONE_A[2 * j],
                            TONE_A[2 * j + 1] };
    float *p = io->io, x[WVFX_MAX_FRAMES], vol[WVFX_MAX_FRAMES], buf[STAGE_BLOCK_PTS];
    const int n = io->frames <= WVFX_MAX_FRAMES ? io->frames : WVFX_MAX_FRAMES;
    if (!io->enabled || n <= 0) {
        for (int i = 0; i < n; i++)
            s->volume = st_glide(s->volume, target);
        return;
    }
    /* stage by stage over the block (Drive, not glided, before the first sample: m is the block's; Volume's glide
       once per sample): the same samples as sample by sample */
    if (s->drive != d) {
        s->drive = d;
        gain_set(&s->gain, g);
    }
    float r = 1.0f / st_fma(s->drive, 10.0f, 1.0f);
    float m = st_fma(st_fma(r, 0.5638300180435181f, 0.09240099787712097f), r, 0.34376999735832214f);
    m = st_fma(st_fma(s->drive, 0.18619200587272644f, -0.5430200099945068f), s->drive, m);
    for (int i = 0; i < n; i++) {
        s->volume = st_glide(s->volume, target);
        vol[i] = s->volume;
        x[i] = fos_run(&s->gain, &s->gs, p[2 * i]);
    }
    STAGE_BLOCK_POINTS(&s->st, x, n, buf, clip_warm(v, m));
    stage_block_fir(&s->st, buf, x, n);
    sos_block(&tc, &s->ts, x, n);
    for (int i = 0; i < n; i++)
        p[2 * i] = p[2 * i + 1] = (vol[i] * 0.8999999761581421f) * x[i];
}

