/* one tap's window weight from its phase: between two points, each part shifted down on its own */
static inline int shift_window(int ph)
{
    int c = (ph >> 5) & 0x7f, k = ph >> 12;
    return ((SHIFT_WINDOW[k + 1] * c) >> 7) + ((SHIFT_WINDOW[k] * (0x80 - c)) >> 7);
}

