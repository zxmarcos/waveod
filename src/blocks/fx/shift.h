/* a phase moved by d (in float, as the original) and wrapped into 0 .. 2^20 */
static inline int shift_step(int ph, float d)
{
    int p = (int)((float)ph + d);
    return p > 0x100000 ? p - 0x100000 : p < 0 ? p + 0x100000 : p;
}

/* a tap's two samples behind the write position nw: a at the phase's whole part, b the one before it */
static inline void shift_pair(const float *line, int nw, int ph, float *a, float *b)
{
    int i = nw - (ph >> 8);
    if (i < 0)
        i += SHIFT_LINE;
    *a = line[i];
    *b = line[(i <= 0 ? i + SHIFT_LINE : i) - 1];
}

/* the read between them by the phase's 8 low bits f, (256 - f) a + f b, in the two orders the modules fuse it */
static inline float shift_read(const float *line, int nw, int ph)
{
    float a, b, f = (float)(ph & 0xff);
    shift_pair(line, nw, ph, &a, &b);
    return st_fma(b, f, (256.0f - f) * a);
}

static inline float shift_read_b(const float *line, int nw, int ph)
{
    float a, b, f = (float)(ph & 0xff);
    shift_pair(line, nw, ph, &a, &b);
    return st_fma(256.0f - f, a, b * f);
}
