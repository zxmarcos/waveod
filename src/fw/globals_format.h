/*
 * The original's global settings: record 0 of the record store, a copy of the first 0x238 bytes of its state
 * block (0x202381A8 in V1.2.2; read at start-up by FUN_000399F0, factory values at 0x42E04 when absent).
 * Both firmwares share it, so a setting changed in one is kept by the other.
 *
 * Offsets (from the editor protocol's settings reply, FUN_0002D120, and the audio loop FUN_00031E18):
 *   +0x000 u16 0x5AA5        +0x006 u16 record size   +0x00C u16 power-up preset (fw/presets.c)
 *   +0x011 auto cab          +0x012 language          +0x014 display mode[2]   +0x016 backlight
 *   +0x018 u16 standby       +0x01A i8 input level (dB, -20..20)                +0x01B input mode
 *   +0x01C no cab on L / R   +0x01E i8 USB record level   +0x01F i8 USB monitor level
 *   +0x020 USB records AUX IN   +0x021 USB record L / R processed   +0x024 EXP 2 jack: 0 pedal, 1 one footswitch,
 *   2 two footswitches   +0x025 / +0x027 function of external footswitch 1 / 2 (the footswitch function codes)
 *   +0x02D bank mode         +0x02F footswitch group (0 = stomp mode, 1 = preset mode)
 *   +0x064 i16 EXP 1 / 2 calibrated maximum   +0x068 i16 minimum   +0x06C i16 toe switch threshold (0..255)
 *   +0x070 i16 MIDI channels: input TRS, input USB, output TRS, output USB   +0x078 MIDI source
 *   +0x079 clock source      +0x07A clock out         +0x07B global EQ on      +0x07C f32 global EQ[31]
 *   +0x0FC looper record level, +0x0FD play level (0..100), +0x0FE place (0 PRE, 1 POST), +0x0FF undo, +0x100 sync,
 *   +0x101 auto record (the last two cleared at every start)
 *   +0x106 u16 drum genre, +0x108 u16 pattern in the genre, +0x10A u16 drum BPM, +0x10C drum follows the tempo,
 *   +0x10D drum volume, +0x118 names of the drum genres of an older pattern set   +0x230 USB device mode   +0x232 AUX IN level 0..100
 *   +0x233 tempo mode        +0x234 u16 global BPM (40..300, 0xFFFF = none)
 * Only the fields below are decoded; the rest is kept as stored.
 */
#pragma once

#include <stdint.h>

#define GLOBALS_RECORD_SIZE 0x238
#define GLOBALS_MAGIC       0x5AA5u
#define EQ_PARAMS           31

/* Global EQ parameters, in record order: switch / frequency / Q (/ gain dB) of each stage, then the level. */
enum eq_param {
    EQ_LOCUT_ON, EQ_LOCUT_F, EQ_LOCUT_Q,
    EQ_LOSHELF_ON, EQ_LOSHELF_F, EQ_LOSHELF_Q, EQ_LOSHELF_G,
    EQ_B1_ON, EQ_B1_F, EQ_B1_Q, EQ_B1_G,
    EQ_B2_ON, EQ_B2_F, EQ_B2_Q, EQ_B2_G,
    EQ_B3_ON, EQ_B3_F, EQ_B3_Q, EQ_B3_G,
    EQ_B4_ON, EQ_B4_F, EQ_B4_Q, EQ_B4_G,
    EQ_HISHELF_ON, EQ_HISHELF_F, EQ_HISHELF_Q, EQ_HISHELF_G,
    EQ_HICUT_ON, EQ_HICUT_F, EQ_HICUT_Q,
    EQ_LEVEL,
};

enum input_mode { INPUT_ACOUSTIC, INPUT_ELECTRIC, INPUT_LINE, INPUT_MODES = 4 };

/* what the EXP 2 jack takes: an expression pedal or one / two footswitches (the original's keys 0x1A / 0x1B) */
enum exp2_jack { EXP2_PEDAL, EXP2_ONE_SWITCH, EXP2_TWO_SWITCHES };

struct eq_param_range {
    float min, max, step, def;
};

/* globals_default.c (generated by tools/gen_defaults.py) */
extern const uint8_t globals_factory[GLOBALS_RECORD_SIZE];
extern const struct eq_param_range eq_param_ranges[EQ_PARAMS];

struct globals {
    uint8_t auto_cab;
    uint8_t backlight;              /* percent */
    int8_t input_level;             /* dB, -20..20 */
    uint8_t input_mode;             /* enum input_mode, 0..3 */
    uint8_t no_cab[2];              /* cabinets / IRs left out of output L / R */
    uint8_t eq_on;
    float eq[EQ_PARAMS];
    uint8_t aux_level;              /* 0..100 */
    uint8_t fs_group;               /* enum fs_group: the mode the pedal starts in */
    int16_t exp_max[2], exp_min[2]; /* expression pedal calibration, 0..255 */
    int16_t exp_toe[2];             /* EXP 1: above this the toe switch flips A / B */
    uint8_t exp2_jack;              /* enum exp2_jack */
    uint8_t loop_rec, loop_play;    /* looper levels, 0..100 */
    uint8_t loop_post, loop_undo;
    uint16_t drum_genre, drum_pattern;  /* genre 0..7 and pattern within it */
    uint16_t drum_bpm;                  /* 40..300 */
    uint8_t drum_sync;                  /* follows the effects' tempo instead */
    uint8_t drum_volume;                /* 0..100 */
    int8_t ext_fn[2];               /* function of the jack's footswitches (enum fs_function) */
    uint8_t tempo_mode;
    uint16_t bpm;                   /* 40..300, 0 = none */
    int8_t usb_rec_level;           /* USB recording level, dB -20..20 (channels 1 / 2) */
    int8_t usb_mon_level;           /* computer playback into the outputs, dB -20..20 */
    uint8_t usb_rec_aux;            /* AUX IN goes into the USB recording too */
    uint8_t usb_rec_wet[2];         /* recording channel 1 / 2: 0 = dry guitar, 1 = processed */
    uint8_t usb_mode;               /* enum usb_mode: 0 = 6-In 4-Out (factory), 1 = 2-In 2-Out */
    /* MIDI (midi/midi.h): input channels of TRS / USB (0 = omni, 1..16), output channels (-1 = off, 0 = omni;
       kept for the original, which hands them to the effect modules only) */
    int16_t midi_channel[4];
    uint8_t midi_source;            /* 0 TRS, 1 USB, 2 both */
    uint8_t clock_source;           /* 0 internal, 1 TRS, 2 USB, 3 external (TRS or USB), 4 mixed */
    uint8_t clock_out;              /* bit 0 TRS, bit 1 USB */
    uint8_t raw[GLOBALS_RECORD_SIZE];   /* the record decoded (or the factory one): the fields not decoded */
};

/* Decode a stored record; -1 when it is not a settings record (out then holds the factory values).
   Out-of-range values are brought back in range like the original's readers do. */
int globals_decode(const uint8_t *rec, struct globals *out);

/* The decoded fields written over `base` (g->raw, a stored record, or globals_factory). */
void globals_encode(const struct globals *g, const uint8_t *base, uint8_t out[GLOBALS_RECORD_SIZE]);
