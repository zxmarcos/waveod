static const char *const strings[USB_STRINGS] = {
    0, "Sonicake", "Matribox II PRO", "20240618", "Matribox II PRO HS Config", "Matribox II PRO Audio",
    "Matribox II PRO MIDI",
};

int usb_desc_string(int index, uint8_t *out, int max)
{
    if (index < 0 || index >= USB_STRINGS || max < 4)
        return -1;
    if (index == 0) {                       /* language: US English */
        out[0] = 4;
        out[1] = 3;
        out[2] = 0x09;
        out[3] = 0x04;
        return 4;
    }
    int n = 2;
    for (const char *c = strings[index]; *c && n + 2 <= max; c++) {
        out[n++] = (uint8_t)*c;
        out[n++] = 0;
    }
    out[0] = (uint8_t)n;
    out[1] = 3;
    return n;
}