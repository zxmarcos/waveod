"""Generate src/model/param_format_table.c from tools/data/display_formats.txt.

The text file lists the parameter display formats of the original app (switch at 0x1B6AC in V1.2.2, one
line per f3 code): either an option list or printf-like templates, several alternatives separated by " / ".

    python tools/gen_formats.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, 'data', 'display_formats.txt')
OUT = os.path.join(os.path.dirname(HERE), 'src', 'model', 'param_format_table.c')


def c_str(s):
    s = s.replace('Â°', '°')
    out = ''
    for ch in s.encode('utf-8'):
        if ch == 0x22 or ch == 0x5c:
            out += '\\' + chr(ch)
        elif 0x20 <= ch < 0x7f:
            out += chr(ch)
        else:
            out += '\\x%02x""' % ch
    return '"%s"' % out


def classify(alts):
    """kind + templates of a printf line"""
    if len(alts) == 1:
        return 'FMT_PRINTF', alts
    a, b = alts[0], alts[1]
    if a in ('Off', 'Mute'):
        return 'FMT_MIN_WORD', alts
    if a == 'Limit':
        return 'FMT_MAX_WORD', alts
    if a == 'Center':
        return 'FMT_PAN', alts
    if a.startswith('+'):
        return 'FMT_SIGNED', alts
    if 'kHz' in b or b.endswith('s') and 'ms' in a:
        return 'FMT_THOUSANDS', alts
    raise ValueError('unknown alternative format %r' % alts)


def main():
    lists, rows = [], []
    for line in open(SRC, encoding='utf-8-sig'):
        m = re.match(r'(0x[0-9a-f]+)\s+(list\[[^\]]*\]|format)\s+(.*)$', line.rstrip('\n'))
        if not m:
            continue
        code, kind, rest = int(m.group(1), 16), m.group(2), m.group(3).strip()
        if kind.startswith('list'):
            opts = [o.strip() for o in rest.split('|')]
            while opts and opts[-1] in ('Error', 'NULL'):
                opts.pop()
            name = 'list_%02x' % code
            lists.append('static const char *const %s[] = {%s, 0};' % (name, ', '.join(c_str(o) for o in opts)))
            rows.append('    [0x%02x] = { FMT_LIST, %s, { 0 } },' % (code, name))
        elif '%' in rest and 'uVar' not in rest and 'FUN_' not in rest:
            k, alts = classify([a.strip() for a in rest.split(' / ')])
            rows.append('    [0x%02x] = { %s, 0, { %s } },' % (code, k, ', '.join(c_str(a) for a in alts)))
        # anything else (lookups into other tables) falls back to the plain number
    n = max(int(r.split(']')[0].split('[')[1], 16) for r in rows) + 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('/* Generated by tools/gen_formats.py from tools/data/display_formats.txt: do not edit. */\n')
        f.write('#include "model/param_format.h"\n\n')
        f.write('\n'.join(lists) + '\n\n')
        f.write('const struct param_format param_formats[PARAM_FORMAT_COUNT] = {\n')
        f.write('\n'.join(rows) + '\n};\n')
    print('%s: %d formats, table size %#x' % (OUT, len(rows), n))


if __name__ == '__main__':
    main()
