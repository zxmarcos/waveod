"""The tables of the original's 512-point real FFT (src/blocks/fx/fft_tables.h, docs/stock_port.md).

    python tools/gen_stock_fft.py STOCK.bin

The original's Harmony D (FX, id 0x0100004E) runs CMSIS-DSP's arm_rfft_fast_f32 for 512 points (a 256-point
complex FFT, radix 8 by 4, and the real split). Its tables are read from the module's symbols: twiddleCoef_256 (256
complex twiddles), twiddleCoef_rfft_512 (the split's 256) and armBitRevIndexTable256 (220 swaps as byte offsets),
written with the shortest decimals that give the same floats. Needs matribox-studio (pip install -e).
"""
import os
import struct
import sys

from matribox.firmware import fwtool

from gen_stock_tapers import shortest, symbols

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'src', 'blocks', 'fx', 'fft_tables.h')
ID = 0x0100004E


def main():
    fw = fwtool.Firmware(open(sys.argv[1], 'rb').read())
    e = next(e for e in fw.library.entries if e.id == ID)
    syms, secs = symbols(e.elf)
    srom = secs['ER_SROM']

    def data(name, fmt, size):
        val, sz = syms[name]
        if sz != size:
            sys.exit('%s: %d bytes' % (name, sz))
        n = size // struct.calcsize(fmt)
        return struct.unpack_from('<%d%s' % (n, fmt), e.elf, srom[4] + val - srom[3])

    lines = ['/* The tables of the original\'s 512-point real FFT (CMSIS-DSP\'s, as the Harmony D module holds them).',
             ' * Generated by tools/gen_stock_fft.py from the original\'s module; do not edit. */',
             '#pragma once', '', '#include <stdint.h>', '']
    for name, cname in (('twiddleCoef_256', 'FFT_TW256'), ('twiddleCoef_rfft_512', 'FFT_TW_RFFT512')):
        v = data(name, 'f', 2048)
        lines.append('static const float %s[512] = {' % cname)
        for i in range(0, 512, 6):
            lines.append('    ' + ', '.join(shortest(x) + 'f' for x in v[i:i + 6]) + ',')
        lines.append('};')
        lines.append('')
    b = data('armBitRevIndexTable256', 'H', 880)
    lines.append('/* pairs of byte offsets (x 8 per complex) to swap */')
    lines.append('static const uint16_t FFT_BITREV256[440] = {')
    for i in range(0, 440, 12):
        lines.append('    ' + ', '.join(str(x) for x in b[i:i + 12]) + ',')
    lines.append('};')
    lines.append('')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
