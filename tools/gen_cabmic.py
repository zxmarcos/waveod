"""Generate src/engine/cabmic_tables.c, the virtual mic's curves, from the JSON of the cab captures' analysis.

    python tools/gen_cabmic.py mic_axes.json [--mics 0,5]

The curves are the medians, over the captures' 46 cabs and 12 mics, of how the response changes along each mic
axis (position: 4 steps from the dust cap to the edge of the cone; distance: 6 steps from the grille outwards;
angle: on axis and 45 degrees), in third octaves, relative to the first step. Smoothed over three bands.

The mic types (--mics: indices into the 12, in the banks' order, docs/cab.md; default the 57 only): each one's
curve against the median of the 12 (a factory IR is taken to be captured with an unknown mic: the median, which
is also what the factory IRs look like, docs/cab.md) and its own axes (that mic's medians over the
46 cabs). CABMIC_TYPES in engine/cabmic.h must match.
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def smooth(c):
    return [c[0]] + [0.25 * c[i - 1] + 0.5 * c[i] + 0.25 * c[i + 1] for i in range(1, len(c) - 1)] + [c[-1]]


def row(c, indent='    '):
    return indent + '{ ' + ', '.join('%.2ff' % v for v in smooth(c)) + ' },'


def table(name, curves):
    lines = ['const float %s[%d][CABMIC_BANDS] = {' % (name, len(curves))]
    lines += [row(c['median']) for c in curves]
    lines.append('};')
    return '\n'.join(lines)


def type_table(name, types, axis, steps):
    lines = ['const float %s[CABMIC_TYPES][%s][CABMIC_BANDS] = {' % (name, steps)]
    for t in types:
        lines.append('    {   /* %s */' % t['name'])
        lines += [row(c['median'], '        ') for c in t[axis]]
        lines.append('    },')
    lines.append('};')
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('json')
    ap.add_argument('--mics', default='0')
    a = ap.parse_args()
    d = json.load(open(a.json))
    types = [d['types'][int(m)] for m in a.mics.split(',')]
    out = ['/* Generated by tools/gen_cabmic.py from the cab captures\' analysis (medians over 46 cabs',
           '   x 12 mics, relative to the first step, dB per third octave, smoothed over 3 bands; the mic types: each',
           '   one against the median of the 12, and its own axes). Do not edit. */',
           '#include "engine/cabmic.h"', '',
           '#if CABMIC_TYPES != %d' % len(types),
           '#error "CABMIC_TYPES does not match the generated tables (tools/gen_cabmic.py --mics)"',
           '#endif', '',
           'const float cabmic_bands[CABMIC_BANDS] = { ' + ', '.join('%.1ff' % b for b in d['bands']) + ' };', '',
           table('cabmic_position', d['position']), '',
           table('cabmic_distance', d['distance']), '',
           table('cabmic_angle', d['angle']), '',
           'const char *const cabmic_type_names[CABMIC_TYPES] = { ' +
           ', '.join('"%s"' % t['name'] for t in types) + ' };', '',
           'const float cabmic_type_curve[CABMIC_TYPES][CABMIC_BANDS] = {']
    out += [row(t['vs_median']) + '   /* %s */' % t['name'] for t in types]
    out += ['};', '',
            type_table('cabmic_type_position', types, 'position', 'CABMIC_POSITIONS'), '',
            type_table('cabmic_type_distance', types, 'distance', 'CABMIC_DISTANCES'), '',
            type_table('cabmic_type_angle', types, 'angle', '2'), '']
    path = os.path.join(ROOT, 'src', 'engine', 'cabmic_tables.c')
    open(path, 'w', newline='\n').write('\n'.join(out))
    print(path, len(d['bands']), 'bands,', len(types), 'mic types:', ', '.join(t['name'] for t in types))


if __name__ == '__main__':
    main()
