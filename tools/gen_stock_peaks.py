"""The table-driven peak sections of the AC Woody and Guitar EQ 2 (src/blocks/dyn/dyn_woody.h,
src/blocks/eq/eq_guitar_2_tab.h; docs/stock_port.md).

    python tools/gen_stock_peaks.py STOCK.bin

The original's AC Woody (DYN, id 0x01000000) and Guitar EQ 2 (EQ, id 0x01000036) look their peak sections up in
tables of 63 points by a knob: numPeakN (b0, b1, b2) and denPeakN (a1, a2) (the original's names; values to 6
decimals, measured, not formulas). Read from each module's symbols and written with the shortest decimals that give
the same floats, one section { b0, b1, b2, 1, a1, a2 } per row. Needs matribox-studio (pip install -e).
"""
import os
import struct
import sys

from matribox.firmware import fwtool

from gen_stock_tapers import shortest, symbols

HERE = os.path.dirname(os.path.abspath(__file__))
BLOCKS = os.path.join(os.path.dirname(HERE), 'src', 'blocks')
POINTS = 63
TABLES = [
    (0x01000000, ['1', '2', '3', '4', '5', '100'], 'WOODY_PEAK', os.path.join(BLOCKS, 'dyn', 'dyn_woody.h'),
     'The AC Woody\'s peak sections: { b0, b1, b2, 1, a1, a2 } at the 63 points the Shape knob picks'),
    (0x01000036, ['1', '2', '3', '4', '5'], 'GEQ2_PEAK', os.path.join(BLOCKS, 'eq', 'eq_guitar_2_tab.h'),
     'The Guitar EQ 2\'s peak sections: { b0, b1, b2, 1, a1, a2 } at the 63 points each band\'s knob picks'),
]


def main():
    fw = fwtool.Firmware(open(sys.argv[1], 'rb').read())
    for eid, peaks, prefix, out, what in TABLES:
        e = next(e for e in fw.library.entries if e.id == eid)
        syms, secs = symbols(e.elf)
        srom = secs['ER_SROM']

        def table(name, cols):
            val, size = syms[name]
            if size != POINTS * cols * 4:
                sys.exit('%s: %d bytes' % (name, size))
            v = struct.unpack_from('<%df' % (POINTS * cols), e.elf, srom[4] + val - srom[3])
            return [v[i:i + cols] for i in range(0, len(v), cols)]

        lines = ['/* %s' % what,
                 ' * (the original\'s numPeakN / denPeakN). Generated by tools/gen_stock_peaks.py from the original\'s',
                 ' * module; do not edit. */',
                 '#pragma once', '', '#include "../amps/amp.h"', '']
        for n in peaks:
            num, den = table('numPeak' + n, 3), table('denPeak' + n, 2)
            lines.append('static const struct sos %s%s[%d] = {' % (prefix, n, POINTS))
            for b, a in zip(num, den):
                lines.append('    { %s },' % ', '.join(shortest(x) + 'f' for x in (b[0], b[1], b[2], 1.0, a[0], a[1])))
            lines.append('};')
            lines.append('')
        open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
        print('wrote', out)


if __name__ == '__main__':
    main()
