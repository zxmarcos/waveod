"""The original's potentiometer tapers for the ported blocks (src/blocks/amps/stock_tapers.h, docs/stock_port.md).

    python tools/gen_stock_tapers.py STOCK.bin

The original's effects look their knobs up in 256-point tables (knob x 2.55), the same in every module that has one
(TAPERS below; measured curves rounded to 4 decimals, not formulas). They are read from the first module of the
library that has each, by the module's symbol (the others are checked to hold the same table), and written with the
shortest decimals that give the same floats. Needs matribox-studio (pip install -e).
"""
import os
import struct
import sys

from matribox.firmware import fwtool

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'src', 'blocks', 'amps', 'stock_tapers.h')
TAPERS = ['pow2', 'pow3', 'pow2_5', 'pow0_5', 'B25', 'pow6', 'A25', 'Cp', 'pow4', 'pow4_5', 'pow3_5', 'pow1_5', 'A25v3', 'pow2_100',
          'Vol', 'C', 'C25', 'At', 'A25_0_0_8', 'B25v2',
          'B25v3', 'pow0_3', 'pow0_1', 'pow5', 'gainLine', 'volumeLine', 'level', 'repeat', 'pow0_4', 'pow0_2', 'pow0_7', 'Clip', 'mid',
          'BassLine', 'VolumeLine', 'Body', 'Top', 'Vol_0', 'B', 'A25v1']
# the C names that are not the symbol in lower case (VolumeLine is not volumeLine's curve)
CNAMES = {'VolumeLine': 'volumeline_fet'}


def symbols(elf):
    shoff, = struct.unpack_from('<I', elf, 32)
    shnum, shstrndx = struct.unpack_from('<HH', elf, 48)
    secs = [struct.unpack_from('<10I', elf, shoff + 40 * i) for i in range(shnum)]
    so = secs[shstrndx][4]
    name = lambda o, base: elf[base + o:elf.index(b'\0', base + o)].decode('latin1')
    names = [name(s[0], so) for s in secs]
    by = dict(zip(names, secs))
    ds, dstr = by['.dynsym'], by['.dynstr']
    out = {}
    for j in range(ds[5] // 16):
        nm, val, size, info, other, shn = struct.unpack_from('<IIIBBH', elf, ds[4] + 16 * j)
        out[name(nm, dstr[4])] = (val, size)
    return out, by


def shortest(v):
    want = struct.pack('<f', v)
    for n in range(1, 10):
        s = '%.*g' % (n, v)
        if struct.pack('<f', float(s)) == want:
            return s if any(c in s for c in '.e') else s + '.0'
    return '%.9g' % v


def main():
    fw = fwtool.Firmware(open(sys.argv[1], 'rb').read())
    tables, users = {}, {}
    for e in fw.library.entries:
        syms, secs = symbols(e.elf)
        for t in TAPERS:
            val, size = syms.get(t, (0, 0))
            if size not in (404, 1024):                 # 101 points (pow2_100, at (int)knob) or 256
                continue
            srom = secs['ER_SROM']
            v = struct.unpack_from('<%df' % (size // 4), e.elf, srom[4] + val - srom[3])
            users.setdefault(t, []).append(e.name)
            if t not in tables:
                tables[t] = (v, e.name)
            elif tables[t][0] != v:                     # one name, one curve: the ports rely on it
                sys.exit('%s differs between %s and %s' % (t, tables[t][1], e.name))
    lines = ['/* The original\'s potentiometer tapers: the knob 0..100 at point (int)(knob x 2.55), 0..1 (the 101-point',
             ' * ones at point (int)knob).',
             ' * Generated by tools/gen_stock_tapers.py from the original\'s library; do not edit. */',
             '#pragma once', '']
    for t in TAPERS:
        v, src = tables[t]
        lines.append('/* %s (as in %s) */' % (t, src))
        lines.append('static const float st_%s[%d] = {' % (CNAMES.get(t, t.lower()), len(v)))
        for i in range(0, len(v), 8):
            lines.append('    ' + ', '.join(shortest(x) + 'f' for x in v[i:i + 8]) + ',')
        lines.append('};')
        lines.append('')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', OUT, ', '.join('%s from %s' % (t, tables[t][1]) for t in TAPERS))


if __name__ == '__main__':
    main()
