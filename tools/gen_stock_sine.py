"""The sine table of the original's reverbs (src/blocks/reverbs/rvb_sine.h, docs/stock_port.md).

    python tools/gen_stock_sine.py

The Hall-type reverbs fill a 2049-point table in their Init with the C library's sin in double:
table[i] = (float)sin((double)((float)i * 0.0030679617f)) (2 pi / 2048, the product in single precision). The
ports read the same table from flash. Written with the shortest decimals that give the same floats.
"""
import math
import os
import struct

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), 'src', 'blocks', 'reverbs', 'rvb_sine.h')


def f32(x):
    return struct.unpack('<f', struct.pack('<f', x))[0]


def short(v):
    """the shortest decimal that reads back as the same float"""
    for n in range(1, 18):
        s = '%.*g' % (n, v)
        if f32(float(s)) == v:
            break
    if 'e' not in s and '.' not in s:
        s += '.0'
    return s + 'f'


def main():
    step = f32(0.003067961661145091)
    vals = [f32(math.sin(f32(f32(float(i)) * step))) for i in range(2049)]
    lines = ['/* generated by tools/gen_stock_sine.py: sin((float)i * 0.0030679617f) in double, i = 0..2048 */',
             '#pragma once', '', 'static const float RVB_SINE[2049] = {']
    row = '   '
    for v in vals:
        item = ' ' + short(v) + ','
        if len(row) + len(item) > 118:
            lines.append(row)
            row = '   '
        row += item
    lines.append(row)
    lines.append('};')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(OUT, len(vals))


if __name__ == '__main__':
    main()
