"""Generate src/fw/globals_default.c and src/fw/preset_default.c from a stock V1.2.2 update file.

    python tools/gen_defaults.py QME-200_FW_USB_V1.2.2.bin

Three tables of the original application (ITCM image of the MCU section):
  - 0x42E04: the factory global settings, the 0x238-byte record 0 the original writes when the record store
    has none (FUN_000399F0), so waveod can create the same record;
  - 0x428E4: the 31 global EQ parameters, 0x1C bytes each {name, unit, f32 min, max, step, default, flag};
  - 0x434C8: the preset template (0x48C bytes) the original starts an imported preset from (FUN_0002E110):
    no effects, no quick knob / expression / CTRL targets, the factory footswitch functions.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import mkfw

SRC = os.path.join(os.path.dirname(HERE), 'src', 'fw')
DEFAULTS_VA, DEFAULTS_SIZE = 0x42E04, 0x238
EQ_VA, EQ_COUNT, EQ_ENTRY = 0x428E4, 31, 0x1C
PRESET_VA, PRESET_SIZE = 0x434C8, 0x48C


def itcm_image(path):
    _, secs = mkfw.read_frmw(open(path, 'rb').read())
    mcu = secs[0]
    fa, size, dst = struct.unpack_from('<3I', mcu, 0x10)
    if dst != 0:
        sys.exit('unexpected MCU section layout')
    return mcu[fa - 0x20000:fa - 0x20000 + size]


def c_float(v):
    s = repr(float(v))
    return (s if ('.' in s or 'e' in s) else s + '.0') + 'f'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    img = itcm_image(sys.argv[1])
    rec = img[DEFAULTS_VA:DEFAULTS_VA + DEFAULTS_SIZE]
    if struct.unpack_from('<H', rec, 0)[0] != 0x5AA5 or struct.unpack_from('<H', rec, 6)[0] != DEFAULTS_SIZE:
        sys.exit('no settings defaults at %#x: not a V1.2.2 application' % DEFAULTS_VA)
    eq = []
    for i in range(EQ_COUNT):
        lo, hi, step, dflt = struct.unpack_from('<4f', img, EQ_VA + EQ_ENTRY * i + 8)
        eq.append((lo, hi, step, dflt))
    if eq[30][1] != 100.0:
        sys.exit('unexpected global EQ table at %#x' % EQ_VA)

    out = ['/* Generated by tools/gen_defaults.py from the V1.2.2 application; do not edit. */',
           '#include "fw/globals_format.h"', '',
           '/* factory record 0 (0x42E04) */',
           'const uint8_t globals_factory[GLOBALS_RECORD_SIZE] = {']
    for i in range(0, len(rec), 16):
        out.append('    ' + ' '.join('0x%02x,' % b for b in rec[i:i + 16]))
    out += ['};', '', '/* global EQ parameters (0x428E4): min, max, step, default */',
            'const struct eq_param_range eq_param_ranges[EQ_PARAMS] = {']
    for lo, hi, step, dflt in eq:
        out.append('    { %s, %s, %s, %s },' % (c_float(lo), c_float(hi), c_float(step), c_float(dflt)))
    out.append('};')
    write(os.path.join(SRC, 'globals_default.c'), out)

    tmpl = img[PRESET_VA:PRESET_VA + PRESET_SIZE]
    if struct.unpack_from('<HH', tmpl, 0) != (0x5AA5, 1) or struct.unpack_from('<H', tmpl, 6)[0] != PRESET_SIZE:
        sys.exit('no preset template at %#x' % PRESET_VA)
    out = ['/* Generated by tools/gen_defaults.py from the V1.2.2 application; do not edit. */',
           '#include "fw/preset_format.h"', '',
           '/* preset template (0x434C8) */',
           'const uint8_t preset_template[PRESET_RECORD_SIZE] = {']
    for i in range(0, len(tmpl), 16):
        out.append('    ' + ' '.join('0x%02x,' % b for b in tmpl[i:i + 16]))
    out.append('};')
    write(os.path.join(SRC, 'preset_default.c'), out)


def write(path, lines):
    with open(path, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(path)


if __name__ == '__main__':
    main()
