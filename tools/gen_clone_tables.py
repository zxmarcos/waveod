"""The tables of the original's Clone (src/blocks/clone/clone_tables.h, docs/stock_port.md).

    python tools/gen_clone_tables.py STOCK.bin

The original's Clone (CLONE, id 0x0F000000) runs CMSIS-DSP's 128-point complex FFT (radix 8 by 2) and its 128-point
real FFT (a 64-point complex one and the real split), and two half-band IIR resamplers. Its tables are read from the
module: twiddleCoef_64, twiddleCoef_rfft_128 and armBitRevIndexTable64 by name, the 128-point complex FFT's
twiddles and bit reversal through arm_cfft_sR_f32_len128 (fftLen, pTwiddle, pBitRevTable, bitRevLength), and
HT_COEFFS_UP_IIR / HT_COEFFS_DOWN_IIR; written with the shortest decimals that give the same floats. Needs
matribox-studio (pip install -e).
"""
import os
import struct
import sys

from matribox.firmware import fwtool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_stock_tapers import shortest, symbols      # noqa: E402
OUT = os.path.join(os.path.dirname(HERE), 'src', 'blocks', 'clone', 'clone_tables.h')
ID = 0x0F000000


def main():
    fw = fwtool.Firmware(open(sys.argv[1], 'rb').read())
    e = next(e for e in fw.library.entries if e.id == ID)
    syms, secs = symbols(e.elf)
    srom = secs['ER_SROM']

    def at(addr, fmt, n):
        return struct.unpack_from('<%d%s' % (n, fmt), e.elf, srom[4] + addr - srom[3])

    def data(name, fmt, size):
        val, sz = syms[name]
        if sz != size:
            sys.exit('%s: %d bytes' % (name, sz))
        return at(val, fmt, size // struct.calcsize(fmt))

    # the struct's pointers are filled in by relocations: the module loaded as the pedal loads it, then read back
    from matribox.module import effemu
    emu = effemu.Emu(e.elf)
    srom_at = effemu.POOLS[1]                       # ER_SROM of the first module loaded
    s_val, _ = syms['arm_cfft_sR_f32_len128']
    raw = bytes(emu.uc.mem_read(srom_at + s_val - srom[3], 16))
    fft_len, tw_addr, br_addr, br_len = struct.unpack_from('<HxxIIH', raw)
    tw_addr += srom[3] - srom_at                    # back to the module's own addresses
    br_addr += srom[3] - srom_at
    if fft_len != 128 or br_len != 208:
        sys.exit('arm_cfft_sR_f32_len128: %d points, %d swaps' % (fft_len, br_len))

    tables = [
        ('CLONE_TW64', 'f', data('twiddleCoef_64', 'f', 512), 'twiddleCoef_64: 64 complex twiddles'),
        ('CLONE_TW128', 'f', at(tw_addr, 'f', 256), 'the 128-point complex FFT\'s 128 twiddles'),
        ('CLONE_TW_RFFT128', 'f', data('twiddleCoef_rfft_128', 'f', 512), 'twiddleCoef_rfft_128: the split\'s 64'),
        ('CLONE_BITREV64', 'H', data('armBitRevIndexTable64', 'H', 112), 'armBitRevIndexTable64: pairs of byte offsets'),
        ('CLONE_BITREV128', 'H', at(br_addr, 'H', 208), 'the 128-point FFT\'s: pairs of byte offsets'),
        ('CLONE_UP_IIR', 'f', data('HT_COEFFS_UP_IIR', 'f', 112), 'HT_COEFFS_UP_IIR: 7 + 5 all-pass coefficients used'),
        ('CLONE_DOWN_IIR', 'f', data('HT_COEFFS_DOWN_IIR', 'f', 96), 'HT_COEFFS_DOWN_IIR: 6 + 4 used'),
    ]
    lines = ['/* The tables of the original\'s Clone (CMSIS-DSP\'s FFT tables and the resamplers\' coefficients, as the',
             ' * module holds them). Generated by tools/gen_clone_tables.py from the original\'s module; do not edit. */',
             '#pragma once', '', '#include <stdint.h>', '']
    for cname, fmt, v, what in tables:
        lines.append('/* %s */' % what)
        if fmt == 'f':
            lines.append('static const float %s[%d] = {' % (cname, len(v)))
            for i in range(0, len(v), 6):
                lines.append('    ' + ', '.join(shortest(x) + 'f' for x in v[i:i + 6]) + ',')
        else:
            lines.append('static const uint16_t %s[%d] = {' % (cname, len(v)))
            for i in range(0, len(v), 12):
                lines.append('    ' + ', '.join(str(x) for x in v[i:i + 12]) + ',')
        lines.append('};')
        lines.append('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
