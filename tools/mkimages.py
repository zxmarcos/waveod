"""Generate src/ui/images/logo.c from assets/logo/waveod_logo.png (the boot animation's pieces).

    python tools/mkimages.py            (needs Pillow)

The logo is cut into its three bands (the wave with the pedal, the "WaveOD" word, the tagline), each trimmed to
what is lit, scaled to fit the 480 x 272 display (one factor for all, so they keep their proportions) and
stored as RGB888 LVGL images (blue, green, red per pixel) on the logo's own black. The boot screen
(src/ui/boot.c) places them with the offsets written next to them.
"""
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'assets', 'logo', 'waveod_logo.png')
OUT = os.path.join(ROOT, 'src', 'ui', 'images', 'logo.c')
HDR = os.path.join(ROOT, 'src', 'ui', 'images', 'logo.h')
SCALE = 0.42                    # 1000-pixel wide word -> 420 pixels
THRESHOLD = 40                  # a channel above this is part of the logo
NAMES = ('logo_wave', 'logo_word', 'logo_tagline')


def bands(im):
    """(top, bottom) of each horizontal band with lit pixels"""
    w, h = im.size
    px = im.load()
    lit = [y for y in range(h) if any(max(px[x, y]) > THRESHOLD for x in range(w))]
    out = []
    for y in lit:
        if out and y == out[-1][1] + 1:
            out[-1][1] = y
        else:
            out.append([y, y])
    return out


def columns(im, top, bottom):
    w, _ = im.size
    px = im.load()
    xs = [x for x in range(w) if any(max(px[x, y]) > THRESHOLD for y in range(top, bottom + 1))]
    return xs[0], xs[-1]


def main():
    im = Image.open(SRC).convert('RGB')
    found = bands(im)
    if len(found) != 3:
        sys.exit('expected three bands in the logo, found %d' % len(found))
    origin_y = found[0][0]
    lefts = []
    pieces = []
    for (top, bottom) in found:
        left, right = columns(im, top, bottom)
        lefts.append(left)
        pieces.append((left, top, right + 1, bottom + 1))
    origin_x = min(lefts)
    right_edge = max(p[2] for p in pieces)

    out = ['/* Generated by tools/mkimages.py from assets/logo/waveod_logo.png; do not edit. */',
           '#include "ui/images/logo.h"', '']
    hdr = ['/* Generated by tools/mkimages.py; do not edit. Pieces of the logo for the boot animation. */',
           '#pragma once', '', '#include "lvgl.h"', '',
           '#define LOGO_W %d' % round((right_edge - origin_x) * SCALE),
           '#define LOGO_H %d' % round((found[-1][1] + 1 - origin_y) * SCALE), '']
    for name, box in zip(NAMES, pieces):
        piece = im.crop(box)
        w, h = round(piece.width * SCALE), round(piece.height * SCALE)
        piece = piece.resize((w, h), Image.LANCZOS)
        rgb = piece.tobytes()
        data = bytearray(len(rgb))
        data[0::3], data[1::3], data[2::3] = rgb[2::3], rgb[1::3], rgb[0::3]
        x, y = round((box[0] - origin_x) * SCALE), round((box[1] - origin_y) * SCALE)
        hdr.append('/* %s: %d x %d at %d, %d of the logo */' % (name, w, h, x, y))
        hdr.append('extern const lv_image_dsc_t %s;' % name)
        hdr.append('#define %s_X %d' % (name.upper(), x))
        hdr.append('#define %s_Y %d' % (name.upper(), y))
        out.append('static LV_ATTRIBUTE_LARGE_CONST const uint8_t %s_data[] = {' % name)
        for i in range(0, len(data), 24):
            out.append('    ' + ' '.join('0x%02x,' % v for v in data[i:i + 24]))
        out += ['};', '',
                'const lv_image_dsc_t %s = {' % name,
                '    .header = { .magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB888, .w = %d, .h = %d, '
                '.stride = %d },' % (w, h, 3 * w),
                '    .data_size = sizeof %s_data,' % name,
                '    .data = %s_data,' % name,
                '};', '']
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(out))
    with open(HDR, 'w', newline='\n') as f:
        f.write('\n'.join(hdr) + '\n')
    print(OUT)
    print('\n'.join(hdr[6:]))


if __name__ == '__main__':
    main()
