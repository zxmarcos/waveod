"""Generate config/lv_conf.h from LVGL's lv_conf_template.h with the settings waveod needs.

    python tools/mkconf.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TEMPLATE = os.path.join(ROOT, 'third_party', 'lvgl', 'lv_conf_template.h')
OUT = os.path.join(ROOT, 'config', 'lv_conf.h')

SETTINGS = {
    'LV_COLOR_DEPTH': '32',                     # XRGB8888 frame buffers, like the original app
    'LV_MEM_SIZE': '(1024 * 1024U)',                 # SDRAM; every screen is built at start-up
    'LV_DEF_REFR_PERIOD': '20',
    'LV_DPI_DEF': '128',
    'LV_USE_LOG': '0',
    'LV_FONT_MONTSERRAT_14': '0',
    'LV_FONT_DEFAULT': '&font_body_14',
    'LV_FONT_CUSTOM_DECLARE': 'LV_FONT_DECLARE(font_body_14)',
    'LV_USE_THEME_DEFAULT': '0',
    'LV_USE_THEME_SIMPLE': '0',
    'LV_USE_THEME_MONO': '0',
    'LV_USE_SYSMON': '0',
    'LV_USE_PERF_MONITOR': '0',
    'LV_USE_OBSERVER': '0',
    'LV_USE_IME_PINYIN': '0',
    'LV_USE_FILE_EXPLORER': '0',
    'LV_BUILD_EXAMPLES': '0',
    'LV_ATTRIBUTE_LARGE_CONST': 'WAVEOD_LARGE_CONST',   # fonts and big tables go to SDRAM, not ITCM
}
UNUSED_WIDGETS = ['ANIMIMG', 'ARC', 'BAR', 'BUTTON', 'BUTTONMATRIX', 'CALENDAR', 'CANVAS', 'CHART', 'CHECKBOX',
                  'DROPDOWN', 'IMAGEBUTTON', 'KEYBOARD', 'LED', 'LIST', 'MENU', 'MSGBOX', 'ROLLER', 'SCALE',
                  'SLIDER', 'SPAN', 'SPINBOX', 'SPINNER', 'SWITCH', 'TEXTAREA', 'TABLE', 'TABVIEW', 'TILEVIEW',
                  'WIN', 'LOTTIE']


def main():
    t = open(TEMPLATE, encoding='utf-8-sig').read()
    t = t.replace('#if 0 /*Set it to "1" to enable content*/', '#if 1 /*Set it to "1" to enable content*/', 1)
    settings = dict(SETTINGS)
    settings.update({'LV_USE_' + w: '0' for w in UNUSED_WIDGETS})
    for name, value in settings.items():
        pat = re.compile(r'^([ \t]*#define[ \t]+%s)([ \t]+[^\n]*?)?([ \t]*/\*[^\n]*)?$' % re.escape(name), re.M)
        m = pat.search(t)
        if not m:
            raise SystemExit('lv_conf_template.h has no %s' % name)
        t = t[:m.start()] + m.group(1) + ' ' + value + (m.group(3) or '') + t[m.end():]
    head = ('/* LVGL configuration for waveod: generated by tools/mkconf.py from LVGL v9.2.2 lv_conf_template.h */\n'
            '#ifdef WAVEOD_HOST\n#define WAVEOD_LARGE_CONST\n#else\n'
            '#define WAVEOD_LARGE_CONST __attribute__((section(\".sdram_const\")))\n#endif\n')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(head + t)
    print(OUT)


if __name__ == '__main__':
    main()
